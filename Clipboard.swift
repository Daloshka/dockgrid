// История буфера обмена: текст, файлы и изображения.
// Хранится в ~/Library/Application Support/DockGrid/clipboard (index.json + images/*.png).
import AppKit
import SwiftUI
import CryptoKit
import ApplicationServices

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, files, image }
    var id: String
    var kind: Kind
    var text: String?
    var files: [String]?
    var image: String?
    var width: Int?
    var height: Int?
    var app: String?
    var firstDate: Date
    var date: Date
    var count: Int
    var pinned: Bool
    var hash: String

    var title: String {
        switch kind {
        case .text:
            return String((text ?? "").trimmingCharacters(in: .whitespacesAndNewlines).prefix(300))
                .replacingOccurrences(of: "\n", with: " ⏎ ")
        case .files:
            return (files ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
        case .image:
            return "Изображение \(width ?? 0)×\(height ?? 0)"
        }
    }
}

final class ClipStore: ObservableObject {
    static let shared = ClipStore()
    @Published private(set) var items: [ClipItem] = []

    private let dir: URL
    private let imagesDir: URL
    private let pb = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    private let limit = 200
    private let maxTextBytes = 2_000_000
    // Менеджеры паролей помечают секреты этими типами — такие записи в историю не попадают.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    private init() {
        let fm = FileManager.default
        dir = fm.homeDirectoryForCurrentUser.appendingPathComponent("Library/Application Support/DockGrid/clipboard")
        imagesDir = dir.appendingPathComponent("images")
        try? fm.createDirectory(at: imagesDir, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try? fm.setAttributes([.posixPermissions: 0o700], ofItemAtPath: dir.path)
        lastChange = pb.changeCount
        if let data = try? Data(contentsOf: dir.appendingPathComponent("index.json")),
           let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
    }

    func start() {
        guard timer == nil else { return }
        let t = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.2
        timer = t
    }

    func imageURL(_ item: ClipItem) -> URL? { item.image.map { imagesDir.appendingPathComponent($0) } }

    private func poll() {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        capture()
    }

    private func sha(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    private func capture() {
        let types = pb.types ?? []
        if types.contains(where: { ignoredTypes.contains($0.rawValue) }) { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        let now = Date()
        func make(_ kind: ClipItem.Kind, hash: String) -> ClipItem {
            ClipItem(id: UUID().uuidString, kind: kind, app: app, firstDate: now, date: now, count: 1, pinned: false, hash: hash)
        }
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            let hash = sha(Data(("files\n" + paths.joined(separator: "\n")).utf8))
            if bump(hash) { return }
            var item = make(.files, hash: hash)
            item.files = paths
            insert(item)
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard s.utf8.count <= maxTextBytes else { return }
            let hash = sha(Data(("text\n" + s).utf8))
            if bump(hash) { return }
            var item = make(.text, hash: hash)
            item.text = s
            insert(item)
        } else if let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff)
                    ?? pb.data(forType: NSPasteboard.PasteboardType("public.jpeg"))
                    ?? pb.data(forType: NSPasteboard.PasteboardType("public.heic")),
                  let rep = NSBitmapImageRep(data: raw),
                  let png = pb.data(forType: .png) ?? rep.representation(using: .png, properties: [:]) {
            let hash = sha(png)
            if bump(hash) { return }
            var item = make(.image, hash: hash)
            item.image = item.id + ".png"
            item.width = rep.pixelsWide
            item.height = rep.pixelsHigh
            guard (try? png.write(to: imagesDir.appendingPathComponent(item.image!), options: .atomic)) != nil else { return }
            insert(item)
        }
    }

    /// Уже есть такая запись — поднимаем её наверх вместо дубля.
    private func bump(_ hash: String, counting: Bool = true) -> Bool {
        guard let i = items.firstIndex(where: { $0.hash == hash }) else { return false }
        var item = items.remove(at: i)
        item.date = Date()
        if counting { item.count += 1 }
        items.insert(item, at: 0)
        save()
        return true
    }

    private func insert(_ item: ClipItem) {
        items.insert(item, at: 0)
        var kept = 0
        for old in items where !old.pinned {
            kept += 1
            if kept > limit { removeFiles(of: old) }
        }
        kept = 0
        items.removeAll { old in
            if old.pinned { return false }
            kept += 1
            return kept > limit
        }
        save()
    }

    private func removeFiles(of item: ClipItem) {
        if let url = imageURL(item) { try? FileManager.default.removeItem(at: url) }
    }

    private func save() {
        let enc = JSONEncoder()
        guard let data = try? enc.encode(items) else { return }
        let url = dir.appendingPathComponent("index.json")
        try? data.write(to: url, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }

    /// Кладёт запись обратно в системный буфер.
    func copy(_ item: ClipItem) {
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text ?? "", forType: .string)
        case .files:
            pb.writeObjects((item.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let url = imageURL(item), let png = try? Data(contentsOf: url) {
                pb.setData(png, forType: .png)
                if let tiff = NSImage(data: png)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        }
        lastChange = pb.changeCount  // собственную запись в буфер повторно не захватываем
        _ = bump(item.hash, counting: false)
    }

    func delete(_ item: ClipItem) {
        removeFiles(of: item)
        items.removeAll { $0.id == item.id }
        save()
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func clearUnpinned() {
        for item in items where !item.pinned { removeFiles(of: item) }
        items.removeAll { !$0.pinned }
        save()
    }

    static func thumbnail(_ url: URL, maxPixel: Int) -> NSImage? {
        guard let src = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixel,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
        return NSImage(cgImage: cg, size: NSSize(width: cg.width / 2, height: cg.height / 2))
    }
}

enum Paster {
    /// Cmd+V в активное приложение. Требует разрешения «Универсальный доступ»; без него только просит его.
    static func paste() {
        guard AXIsProcessTrusted() else {
            let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
            _ = AXIsProcessTrustedWithOptions(opts)
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: down)
                e?.flags = .maskCommand
                e?.post(tap: .cghidEventTap)
            }
        }
    }
}

final class ClipModel: ObservableObject {
    @Published var query = "" { didSet { selected = 0 } }
    @Published var selected = 0
    var onClose: ((_ restoreFocus: Bool) -> Void)?
    let store = ClipStore.shared
    private var thumbs: [String: NSImage] = [:]

    var visible: [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        let all = store.items.filter(\.pinned) + store.items.filter { !$0.pinned }
        if q.isEmpty { return all }
        return all.filter { item in
            switch item.kind {
            case .text: return (item.text ?? "").localizedCaseInsensitiveContains(q)
            case .files: return (item.files ?? []).contains { $0.localizedCaseInsensitiveContains(q) }
            case .image: return false
            }
        }
    }

    func thumb(_ item: ClipItem, maxPixel: Int) -> NSImage? {
        let key = "\(item.id)-\(maxPixel)"
        if let hit = thumbs[key] { return hit }
        guard let url = store.imageURL(item), let img = ClipStore.thumbnail(url, maxPixel: maxPixel) else { return nil }
        thumbs[key] = img
        return img
    }

    func move(_ delta: Int) {
        let n = visible.count
        guard n > 0 else { return }
        selected = min(max(selected + delta, 0), n - 1)
    }

    func activate(_ index: Int, paste: Bool) {
        let list = visible
        guard list.indices.contains(index) else { return }
        use(list[index], paste: paste)
    }

    func use(_ item: ClipItem, paste: Bool) {
        onClose?(true)
        store.copy(item)
        if paste { Paster.paste() }
    }

    func deleteSelected() {
        let list = visible
        guard list.indices.contains(selected) else { return }
        store.delete(list[selected])
        selected = min(selected, max(list.count - 2, 0))
    }
}

struct ClipRow: View {
    let item: ClipItem
    let index: Int
    let isSelected: Bool
    @ObservedObject var model: ClipModel
    @State private var hovering = false

    var body: some View {
        HStack(spacing: 8) {
            content
            Spacer(minLength: 6)
            if item.pinned { Image(systemName: "pin.fill").font(.system(size: 10)).opacity(0.7) }
            if index < 9 { Text("⌘\(index + 1)").font(.system(size: 11)).opacity(0.55) }
        }
        .padding(.horizontal, 10).padding(.vertical, 6)
        .foregroundStyle(isSelected ? Color.white : Color.primary)
        .background(RoundedRectangle(cornerRadius: 8)
            .fill(isSelected ? Color.accentColor.opacity(0.85) : Color.primary.opacity(hovering ? 0.07 : 0)))
        .contentShape(Rectangle())
        .onHover { hovering = $0 }
        .onTapGesture { model.use(item, paste: false) }
        .contextMenu {
            Button("Скопировать") { model.use(item, paste: false) }
            Button("Вставить") { model.use(item, paste: true) }
            Divider()
            Button(item.pinned ? "Открепить" : "Закрепить сверху") { model.store.togglePin(item) }
            if item.kind == .files, let first = item.files?.first {
                Button("Показать в Finder") {
                    model.onClose?(false)
                    NSWorkspace.shared.activateFileViewerSelecting([URL(fileURLWithPath: first)])
                }
            }
            Divider()
            Button("Удалить") { model.store.delete(item) }
        }
    }

    @ViewBuilder var content: some View {
        switch item.kind {
        case .text:
            Text(item.title).font(.system(size: 13)).lineLimit(1).truncationMode(.middle)
        case .files:
            HStack(spacing: 6) {
                if let first = item.files?.first {
                    Image(nsImage: NSWorkspace.shared.icon(forFile: first)).resizable().frame(width: 18, height: 18)
                }
                Text(item.title).font(.system(size: 13)).lineLimit(1).truncationMode(.middle)
            }
        case .image:
            if let img = model.thumb(item, maxPixel: 600) {
                Image(nsImage: img).resizable().scaledToFit()
                    .frame(maxWidth: 300, maxHeight: 80, alignment: .leading)
                    .clipShape(RoundedRectangle(cornerRadius: 4))
            } else {
                Text(item.title).font(.system(size: 13)).lineLimit(1)
            }
        }
    }
}

struct ClipPreview: View {
    let item: ClipItem
    @ObservedObject var model: ClipModel

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            Group {
                switch item.kind {
                case .text:
                    ScrollView {
                        Text(String((item.text ?? "").prefix(20_000)))
                            .font(.system(size: 12, design: .monospaced))
                            .frame(maxWidth: .infinity, alignment: .leading)
                    }
                case .files:
                    ScrollView {
                        VStack(alignment: .leading, spacing: 8) {
                            ForEach(item.files ?? [], id: \.self) { path in
                                HStack(spacing: 8) {
                                    Image(nsImage: NSWorkspace.shared.icon(forFile: path)).resizable().frame(width: 28, height: 28)
                                    Text(path).font(.system(size: 12)).lineLimit(3)
                                }
                            }
                        }.frame(maxWidth: .infinity, alignment: .leading)
                    }
                case .image:
                    if let img = model.thumb(item, maxPixel: 1400) {
                        Image(nsImage: img).resizable().scaledToFit()
                            .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .top)
                    }
                }
            }
            .frame(maxHeight: .infinity, alignment: .top)
            Divider()
            VStack(alignment: .leading, spacing: 3) {
                if let app = item.app { Text("Приложение: \(app)") }
                if item.kind == .image { Text("Размер: \(item.width ?? 0)×\(item.height ?? 0)") }
                if item.kind == .text { Text("Символов: \((item.text ?? "").count)") }
                Text("Первое копирование: \(item.firstDate.formatted(date: .abbreviated, time: .shortened))")
                Text("Последнее: \(item.date.formatted(date: .abbreviated, time: .shortened))")
                Text("Копирований: \(item.count)")
            }
            .font(.system(size: 11)).foregroundStyle(.secondary)
        }
        .padding(14)
    }
}

struct ClipView: View {
    @ObservedObject var model: ClipModel
    @ObservedObject var store = ClipStore.shared
    @FocusState private var focused: Bool

    var body: some View {
        let list = model.visible
        VStack(spacing: 0) {
            HStack(spacing: 10) {
                Image(systemName: "doc.on.clipboard").foregroundStyle(.secondary)
                TextField("Поиск в буфере обмена", text: $model.query)
                    .textFieldStyle(.plain).font(.system(size: 18)).focused($focused)
            }
            .padding(.horizontal, 22).padding(.vertical, 14)
            Divider()
            HStack(spacing: 0) {
                VStack(spacing: 0) {
                    ScrollViewReader { proxy in
                        ScrollView {
                            LazyVStack(spacing: 2) {
                                if list.isEmpty {
                                    Text(store.items.isEmpty ? "История пуста — скопируйте что-нибудь" : "Ничего не найдено")
                                        .foregroundStyle(.secondary).padding(.top, 60)
                                }
                                ForEach(Array(list.enumerated()), id: \.element.id) { i, item in
                                    ClipRow(item: item, index: i, isSelected: i == model.selected, model: model)
                                        .id(item.id)
                                }
                            }
                            .padding(8)
                        }
                        .onChange(of: model.selected) { _, new in
                            if list.indices.contains(new) { proxy.scrollTo(list[new].id) }
                        }
                    }
                    Divider()
                    HStack {
                        Text("⏎ скопировать · ⌥⏎ вставить · ⌘⌫ удалить")
                            .font(.system(size: 11)).foregroundStyle(.secondary)
                        Spacer()
                        Button("Очистить") { store.clearUnpinned(); model.selected = 0 }
                            .buttonStyle(.plain).font(.system(size: 11)).foregroundStyle(.secondary)
                    }
                    .padding(.horizontal, 12).padding(.vertical, 8)
                }
                .frame(width: 450)
                Divider()
                Group {
                    if list.indices.contains(model.selected) {
                        ClipPreview(item: list[model.selected], model: model)
                    } else {
                        Color.clear
                    }
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            }
        }
        .frame(width: 868, height: 640)
        .background(Blur())
        .clipShape(RoundedRectangle(cornerRadius: 18))
        .onAppear { focused = true }
    }
}
